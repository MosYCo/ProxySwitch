async function enableSampleEdits(page: Page) {
  await page.evaluate(async () => {
    const api = (window as unknown as { __TAURI_INTERNALS__: { invoke: (command: string, args?: Record<string, unknown>) => Promise<unknown> } }).__TAURI_INTERNALS__
    const read = api.invoke
    const projects = await read("list_projects") as Project[]
    api.invoke = async (command, args = {}) => {
      if (command === "list_projects") return structuredClone(projects)
      if (command === "create_project") { projects.push(structuredClone(args.project as Project)); return args.project }
      if (command === "update_project") { Object.assign(projects.find(project => project.name === args.name)!, structuredClone(args.project as Project)); return args.project }
      if (command === "create_environment" || command === "update_environment") {
        projects.find(project => project.name === args.project)!.environments[args.name as string] = structuredClone(args.env as Environment)
        return null
      }
      return read(command, args)
    }
  })
}

